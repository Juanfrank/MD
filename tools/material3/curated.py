"""Material 3 data that is not in the @material/web token files (layout, spacing, elevation shadows,
accessibility rules, light/dark algorithm) and the CSS / guideline registry built from tokens + this data.

Every guideline carries a `source`:
  "token"   - extracted from the official @material/web token sources (machine-derived, exact);
  "spec"    - transcribed from the m3.material.io specification by hand (not machine-verified).
"""

BASE_UNIT = 8  # dp; md.sys.measurement.space100 (m3.material.io/styles/spacing/tokens)
# md.sys.measurement.space<N> = N% of the 8dp base unit: 0x-9x plus the nested units 0.25x, 0.5x, 0.75x, 1.25x.
SPACING = {f"space{pct}": pct * BASE_UNIT / 100 for pct in
           (0, 25, 50, 75, 100, 125, 200, 300, 400, 500, 600, 700, 800, 900)}
# Values on which @material/web v0_192 and m3.material.io differ; the site (the spec) wins. Keep in sync with audit.ALT_VALUES.
SITE_OVERRIDES = {"focus-state-layer-opacity": "0.1", "pressed-state-layer-opacity": "0.1"}


def apply_site_overrides(tokens):
    """Applies SITE_OVERRIDES to the extracted state tokens and records them in tokens["overrides"]."""
    tokens["overrides"] = {}
    for k, v in SITE_OVERRIDES.items():
        tokens["overrides"][f"state.{k}"] = {"package": tokens["sys"]["state"][k], "site": v}
        tokens["sys"]["state"][k] = v
    return tokens


# Window size classes: (name, min-width dp, columns, margin dp)
WINDOW_CLASSES = [
    ("compact", 0, 4, 16), ("medium", 600, 8, 24), ("expanded", 840, 12, 24),
    ("large", 1200, 12, 24), ("extra-large", 1600, 12, 24),
]
GUTTER = 8        # dp between columns inside the grid
PANE_SPACER = 24  # dp between panes on large screens
TOUCH_TARGET = 48  # dp minimum
TARGET_GAP = 8     # dp minimum between adjacent targets
ELEVATION_SHADOW = {  # key + ambient shadows per level
    0: "none",
    1: "0 1px 2px 0 rgb(0 0 0 / 0.30), 0 1px 3px 1px rgb(0 0 0 / 0.15)",
    2: "0 1px 2px 0 rgb(0 0 0 / 0.30), 0 2px 6px 2px rgb(0 0 0 / 0.15)",
    3: "0 1px 3px 0 rgb(0 0 0 / 0.30), 0 4px 8px 3px rgb(0 0 0 / 0.15)",
    4: "0 2px 3px 0 rgb(0 0 0 / 0.30), 0 6px 10px 4px rgb(0 0 0 / 0.15)",
    5: "0 4px 4px 0 rgb(0 0 0 / 0.30), 0 8px 12px 6px rgb(0 0 0 / 0.15)",
}
CONTRAST = {"text": 4.5, "large-text-and-ui": 3.0}  # WCAG 2.x ratios M3 targets at the standard level
CONTRAST_LEVELS = {"standard": 0.0, "medium": 0.5, "high": 1.0, "reduced": -1.0}  # DynamicScheme.contrastLevel
VARIANTS = ["monochrome", "neutral", "tonal-spot", "vibrant", "expressive", "fidelity", "content",
            "rainbow", "fruit-salad"]
STATE_OPACITY = {"disabled-container": 0.12, "disabled-content": 0.38}


def _decl(d):
    return "".join(f"  {k}: {v};\n" for k, v in d.items())


def _color_block(tokens, mode):
    return {f"--md-sys-color-{r}": f"var(--md-ref-palette-{m[mode]})" for r, m in sorted(tokens["sys_color"].items())}


def render_css(t):
    o = ["/* Material 3 - generated by tools/material3/build_material3.py. Do not edit by hand.\n"
         "   Tokens: @material/web v0_192 (official), except the state-layer overrides listed in tokens.json (m3.material.io wins). Layout/spacing/elevation shadows: tools/material3/curated.py */\n"]
    root = {}
    root.update({f"--md-ref-palette-{k}": v for k, v in sorted(t["palette"].items())})
    root.update({f"--md-ref-typeface-{k}": v for k, v in sorted(t["typeface"].items())})
    root.update(_color_block(t, "light"))
    root.update({f"--md-sys-{n}-{k}": v for n in ("shape", "state", "motion") for k, v in sorted(t["sys"][n].items())})
    root.update({f"--md-sys-elevation-{k}": f"{v}dp" for k, v in sorted(t["sys"]["elevation"].items())})
    root.update({f"--md-sys-elevation-{k}-shadow": ELEVATION_SHADOW[i]
                 for i, k in enumerate(sorted(t["sys"]["elevation"]))})
    root.update({f"--md-sys-typescale-{k}": v for k, v in sorted(t["typescale"].items())})
    root.update({f"--md-sys-measurement-{k}": f"{v / 16:g}rem" for k, v in SPACING.items()})
    root.update({"--md-sys-layout-gutter": f"{GUTTER / 16}rem", "--md-sys-layout-pane-spacer": f"{PANE_SPACER / 16}rem",
                 "--md-sys-layout-margin": "1rem", "--md-sys-layout-columns": "4",
                 "--md-sys-touch-target": f"{TOUCH_TARGET / 16}rem", "--md-sys-touch-target-gap": f"{TARGET_GAP / 16}rem",
                 "--md-sys-state-disabled-container-opacity": "0.12", "--md-sys-state-disabled-content-opacity": "0.38"})
    o.append(":root {\n  color-scheme: light dark;\n" + _decl(root) + "}\n")
    dark = _decl(_color_block(t, "dark"))
    o.append("/* Dark theme: system preference unless forced, or forced with data-theme */\n"
             "@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n"
             + dark.replace("  --", "    --") + "  }\n}\n")
    o.append(":root[data-theme=\"dark\"] {\n" + dark + "}\n")
    o.append(":root[data-theme=\"light\"] {\n" + _decl(_color_block(t, "light")) + "}\n")
    o.append("/* Contrast: medium/high palettes come from the dynamic-colour contrast curves (DynamicScheme\n"
             "   contrastLevel 0.5 / 1.0); regenerate --md-sys-color-* with them and scope them to these selectors. */\n"
             "@media (prefers-contrast: more) {\n  :root { --md-sys-contrast-level: 1; }\n}\n"
             ":root[data-contrast=\"medium\"] { --md-sys-contrast-level: 0.5; }\n"
             ":root[data-contrast=\"high\"] { --md-sys-contrast-level: 1; }\n"
             ":root { --md-sys-contrast-level: 0; }\n")
    # typography classes: size / line-height / weight / tracking
    for style in sorted({k.rsplit("-", 1)[0] for k in t["typescale"] if k.endswith("-size")}):
        base = f"--md-sys-typescale-{style}"
        o.append(f".md-typescale-{style} {{\n  font-family: var({base}-font);\n  font-size: var({base}-size);\n"
                 f"  line-height: var({base}-line-height);\n  font-weight: var({base}-weight);\n"
                 f"  letter-spacing: var({base}-tracking);\n}}\n")
    for style in ("label-large", "label-medium"):
        o.append(f".md-typescale-{style}-prominent {{ font-weight: var(--md-sys-typescale-{style}-weight-prominent); }}\n")
    # layout: window size classes
    for name, minw, cols, margin in WINDOW_CLASSES[1:]:
        o.append(f"@media (min-width: {minw}px) {{\n  :root {{ --md-sys-layout-columns: {cols}; "
                 f"--md-sys-layout-margin: {margin / 16}rem; }}\n}}\n")
    o.append(".md-layout {\n  display: grid;\n  grid-template-columns: repeat(var(--md-sys-layout-columns), minmax(0, 1fr));\n"
             "  column-gap: var(--md-sys-layout-gutter);\n  padding-inline: var(--md-sys-layout-margin);\n}\n")
    # elevation / shape / state / motion utilities
    for i, k in enumerate(sorted(t["sys"]["elevation"])):
        o.append(f".md-elevation-{i} {{ box-shadow: var(--md-sys-elevation-{k}-shadow); }}\n")
    for k in sorted(t["sys"]["shape"]):
        o.append(f".md-shape-{k.replace('corner-', '')} {{ border-radius: var(--md-sys-shape-{k}); }}\n")
    o.append(".md-state-layer {\n  position: relative;\n}\n.md-state-layer::after {\n  content: \"\";\n  position: absolute;\n"
             "  inset: 0;\n  border-radius: inherit;\n  background: currentColor;\n  opacity: 0;\n  pointer-events: none;\n"
             "  transition: opacity var(--md-sys-motion-duration-short2) var(--md-sys-motion-easing-standard);\n}\n"
             ".md-state-layer:hover::after { opacity: var(--md-sys-state-hover-state-layer-opacity); }\n"
             ".md-state-layer:focus-visible::after { opacity: var(--md-sys-state-focus-state-layer-opacity); }\n"
             ".md-state-layer:active::after { opacity: var(--md-sys-state-pressed-state-layer-opacity); }\n"
             ".md-state-layer[data-dragged]::after { opacity: var(--md-sys-state-dragged-state-layer-opacity); }\n"
             ".md-state-layer:disabled, .md-state-layer[aria-disabled=\"true\"] { opacity: var(--md-sys-state-disabled-content-opacity); }\n")
    o.append(".md-touch-target {\n  min-inline-size: var(--md-sys-touch-target);\n  min-block-size: var(--md-sys-touch-target);\n}\n"
             ".md-focus-ring:focus-visible {\n  outline: 3px solid var(--md-sys-color-secondary);\n  outline-offset: 2px;\n}\n")
    o.append("@media (prefers-reduced-motion: reduce) {\n  :root {\n    --md-sys-motion-duration-short1: 0ms;\n"
             "    --md-sys-motion-duration-short2: 0ms;\n    --md-sys-motion-duration-short3: 0ms;\n"
             "    --md-sys-motion-duration-short4: 0ms;\n  }\n}\n")
    o.append(".md-surface {\n  background: var(--md-sys-color-surface);\n  color: var(--md-sys-color-on-surface);\n}\n"
             ".md-scrim { background: var(--md-sys-color-scrim); opacity: 0.32; }\n")
    # component tokens
    for comp, toks in sorted(t["components"].items()):
        decls = {f"--md-{comp}-{k}": v for k, v in sorted(toks.items())}
        o.append(f"/* {comp} */\n:root {{\n" + _decl(decls) + "}\n")
    return "\n".join(o)


def guidelines(t):
    """The registry: each guideline names the CSS needles that must be present in m3.css."""
    g = []

    def add(gid, cat, title, rule, source, css):
        g.append({"id": gid, "category": cat, "title": title, "rule": rule, "source": source, "css": css})

    # ---- colour roles (token)
    for r, m in sorted(t["sys_color"].items()):
        add(f"color.role.{r}", "color-roles", f"Colour role {r}",
            f"light={m['light']}, dark={m['dark']}", "token",
            [f"--md-sys-color-{r}: var(--md-ref-palette-{m['light']})", f"--md-sys-color-{r}: var(--md-ref-palette-{m['dark']})"])
    for k in sorted(t["palette"]):
        add(f"color.palette.{k}", "reference-palette", f"Reference palette tone {k}", t["palette"][k], "token",
            [f"--md-ref-palette-{k}: {t['palette'][k]}"])
    # ---- typography (token) incl. line spacing
    styles = sorted({k.rsplit("-", 1)[0] for k in t["typescale"] if k.endswith("-size")})
    for s in styles:
        size, lh = t["typescale"][s + "-size"], t["typescale"][s + "-line-height"]
        add(f"type.{s}", "typography", f"Type style {s}",
            f"size {size}, line-height {lh}, tracking {t['typescale'][s + '-tracking']}, weight {t['typescale'][s + '-weight']}",
            "token", [f".md-typescale-{s} {{", f"--md-sys-typescale-{s}-line-height: {lh}",
                      f"--md-sys-typescale-{s}-tracking: {t['typescale'][s + '-tracking']}"])
    for k, v in sorted(t["typeface"].items()):
        add(f"type.typeface.{k}", "typography", f"Typeface token {k}", str(v), "token", [f"--md-ref-typeface-{k}: {v}"])
    # ---- shape / elevation / state / motion (token)
    for k, v in sorted(t["sys"]["shape"].items()):
        add(f"shape.{k}", "shape", f"Shape {k}", v, "token", [f"--md-sys-shape-{k}: {v}", f".md-shape-{k.replace('corner-', '')} "])
    for i, (k, v) in enumerate(sorted(t["sys"]["elevation"].items())):
        add(f"elevation.{k}", "elevation", f"Elevation {k}", f"{v}dp", "token",
            [f"--md-sys-elevation-{k}: {v}dp", f"--md-sys-elevation-{k}-shadow", f".md-elevation-{i} "])
    for k, v in sorted(t["sys"]["state"].items()):
        add(f"state.{k}", "state-layers", f"State {k}", str(v), "site" if k in SITE_OVERRIDES else "token",
            [f"--md-sys-state-{k}: {v}"])
    for k, v in sorted(t["sys"]["motion"].items()):
        add(f"motion.{k}", "motion", f"Motion {k}", v, "token", [f"--md-sys-motion-{k}: {v}"])
    # ---- components (token): every component token must be emitted
    for comp, toks in sorted(t["components"].items()):
        add(f"component.{comp}", "components", f"Component {comp}", f"{len(toks)} design tokens", "token",
            [f"--md-{comp}-{k}: {v}" for k, v in sorted(toks.items())])
    # ---- spec-transcribed guidelines
    for k, v in SPACING.items():
        nested = v and v % BASE_UNIT
        add(f"spacing.{k}", "spacing", f"Spacing {k} = {v:g}dp ({'nested unit' if nested else 'multiple'} of the 8dp base)",
            "Spacing is a multiple of the 8dp base unit (space100); the only nested units are 2, 4, 6 and 10dp", "spec",
            [f"--md-sys-measurement-{k}: {v / 16:g}rem"])
    for name, minw, cols, margin in WINDOW_CLASSES:
        add(f"layout.window.{name}", "layout", f"Breakpoint {name} (>= {minw}dp; formerly window size class)",
            f"{cols} columns, {margin}dp margins", "spec",
            [f"--md-sys-layout-columns: {cols}", f"--md-sys-layout-margin: {margin / 16}rem"] if minw else
            ["--md-sys-layout-columns: 4", "--md-sys-layout-margin: 1rem"])
    add("layout.gutter", "layout", "Column gutter", f"{GUTTER}dp between grid columns (implementation choice: m3.material.io states no gutter value)",
        "impl", ["--md-sys-layout-gutter"])
    add("layout.pane-spacer", "layout", "Pane spacer", f"{PANE_SPACER}dp between panes (medium breakpoint and up)", "spec",
        ["--md-sys-layout-pane-spacer"])
    add("layout.grid", "layout", "Responsive column grid", "Grid with columns and margins per breakpoint", "spec", [".md-layout {"])
    add("a11y.touch-target", "accessibility", "Minimum touch target 48x48dp",
        "Interactive elements are at least 48dp square", "spec", [f"--md-sys-touch-target: {TOUCH_TARGET / 16}rem", ".md-touch-target"])
    add("a11y.touch-gap", "accessibility", "Gap between targets",
        f"At least {TARGET_GAP}dp between adjacent targets", "spec", ["--md-sys-touch-target-gap: 0.5rem"])
    add("a11y.contrast.text", "accessibility", "Text contrast 4.5:1",
        "Text and icons against their container reach 4.5:1 at the standard contrast level", "spec",
        ["--md-sys-color-on-surface", "--md-sys-color-surface"])
    add("a11y.contrast.ui", "accessibility", "Large text / UI contrast 3:1",
        "Large text, icons, input outlines and state indicators reach 3:1", "spec", ["--md-sys-color-outline"])
    for lvl in CONTRAST_LEVELS:
        if lvl in ("medium", "high"):
            add(f"a11y.contrast.level.{lvl}", "accessibility", f"Contrast level {lvl}",
                f"DynamicScheme contrastLevel {CONTRAST_LEVELS[lvl]} (m3.material.io names the levels but gives no numbers; the value comes from material-color-utilities)", "spec", [f"data-contrast=\"{lvl}\""])
    add("a11y.contrast.prefers-more", "accessibility", "Honour prefers-contrast", "Hook only: switch to higher contrast on request (a CSS media query, not an M3 spec item)", "impl",
        ["prefers-contrast: more"])
    add("a11y.reduced-motion", "accessibility", "Honour prefers-reduced-motion", "With reduced motion on: use subtle fades instead of slide/scale, no parallax or shape morphing (m3.material.io). This CSS only zeroes the short durations; transform-based effects are up to the app", "spec",
        ["prefers-reduced-motion: reduce"])
    add("a11y.focus", "accessibility", "Visible focus indicator", "Keyboard focus is clearly visible", "spec", [".md-focus-ring:focus-visible"])
    add("a11y.disabled", "state-layers", "Disabled state", "Disabled container 12%, content 38% opacity", "spec",
        ["--md-sys-state-disabled-container-opacity: 0.12", "--md-sys-state-disabled-content-opacity: 0.38"])
    add("state.layer", "state-layers", "State layer behaviour", "Hover/focus/pressed/dragged overlay on the content colour", "spec",
        [".md-state-layer:hover::after", ".md-state-layer:focus-visible::after", ".md-state-layer:active::after"])
    add("color.theme.light", "light-dark", "Light theme", "Default; roles map to light tones", "spec", [":root[data-theme=\"light\"]"])
    add("color.theme.dark", "light-dark", "Dark theme", "Roles map to dark tones, by preference or data-theme", "spec",
        ["prefers-color-scheme: dark", ":root[data-theme=\"dark\"]"])
    add("color.scrim", "color-roles", "Scrim", "Scrim 32% over content behind modals", "spec", [".md-scrim"])
    add("surface.base", "color-roles", "Surface + on-surface pairing", "Content uses the on-colour of its container", "spec", [".md-surface"])
    return g
